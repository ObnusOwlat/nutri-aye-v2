// HTTP helpers: typed errors, pagination and response shapes
const { randomUUID } = require('crypto');

class HttpError extends Error {
    constructor(status, message, code, details) {
        super(message);
        this.status = status;
        this.code = code;
        this.details = details;
    }
}

const notFound = (what = 'Recurso') => new HttpError(404, `${what} no encontrado`, 'NOT_FOUND');
const badRequest = (message, details) => new HttpError(400, message, 'VALIDATION_ERROR', details);
const conflict = (message) => new HttpError(409, message, 'CONFLICT');

// ?page=&limit= -> safe numbers
function pageParams(query, { defaultLimit = 50, maxLimit = 100 } = {}) {
    const page = Math.max(1, parseInt(query.page, 10) || 1);
    const limit = Math.min(maxLimit, Math.max(1, parseInt(query.limit, 10) || defaultLimit));
    return { page, limit, offset: (page - 1) * limit };
}

function sendPage(res, data, { page, limit }, total) {
    res.json({ success: true, data, pagination: { page, limit, total, totalPages: Math.ceil(total / limit) } });
}

const newId = () => randomUUID(); // ids are always generated by the server
const nowIso = () => new Date().toISOString();

module.exports = { HttpError, notFound, badRequest, conflict, pageParams, sendPage, newId, nowIso };
